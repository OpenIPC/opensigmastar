#!/bin/sh
# kcompat-obj.sh -- a relinked vendor object for a kernel newer than its SDK's
#
# Usage: scripts/kcompat-obj.sh <objcopy> <nm> <renames> <Module.symvers> <in.o> <out.o> <exports.c>
#
# Used by kernel/kcompat/kcompat.kbuild (KCOMPAT=1) only:
#  - renames the vendor's references to kernel functions whose prototype or
#    meaning changed to kcompat_<sym> (objcopy --redefine-syms <renames>),
#    which open_kcompat.ko provides;
#  - takes out the vendor's export table. Since 5.4 a struct kernel_symbol
#    is 12 bytes (a namespace), the vendor's __ksymtab holds 8-byte entries
#    the loader would misread; <exports.c> exports the same symbols again
#    with this kernel's EXPORT_SYMBOL/EXPORT_SYMBOL_GPL;
#  - imports the symbol namespaces (5.4+) of the kernel symbols it uses
#    (Module.symvers), e.g. filp_open's in SigmaStar's 5.10.
set -e

[ $# -eq 7 ] || { sed -n '4p' "$0" >&2; exit 1; }
OBJCOPY=$1 NM=$2 RENAMES=$3 SYMVERS=$4 IN=$5 OUT=$6 EXPORTS=$7

# ko2obj.sh put back one __ksymtab_<sym> per entry, in __ksymtab or
# __ksymtab_gpl: "<sym> <section>"
READELF=${OBJCOPY%objcopy}readelf
{ "$READELF" -SW "$IN"; echo "--symbols--"; "$READELF" -sW "$IN"; } | awk '
	/^--symbols--$/ { syms = 1; next }
	!syms && match($0, /^ *\[ *[0-9]+\] /) {
		i = substr($0, RSTART, RLENGTH); gsub(/[^0-9]/, "", i)
		rest = substr($0, RSTART + RLENGTH); split(rest, f, " ")
		name[i] = f[1]; next
	}
	syms && $8 ~ /^__ksymtab_/ && $8 != "__ksymtab_strings" && $4 == "OBJECT" {
		print substr($8, 11), name[$7]
	}' | sort -u > "$OUT.syms"
{
	echo '/* generated by scripts/kcompat-obj.sh: the vendor object'"'"'s exports */'
	echo '#include <linux/export.h>'
	echo '#include <linux/module.h>'
	while read -r s sec; do
		echo "extern char $s[];"
		if [ "$sec" = "__ksymtab_gpl" ]; then
			echo "EXPORT_SYMBOL_GPL($s);"
		else
			echo "EXPORT_SYMBOL($s);"
		fi
	done < "$OUT.syms"
	"$NM" -u "$IN" | awk '{ print $2 }' | sort -u > "$OUT.undef"
	awk -F '\t' 'NF >= 5 && $5 != "" { print $2, $5 }' "$SYMVERS" | sort -u |
		join - "$OUT.undef" 2>/dev/null | awk '{ print $2 }' | sort -u |
		while read -r ns; do
			echo "MODULE_IMPORT_NS($ns);"
		done
	rm -f "$OUT.undef"
} > "$EXPORTS"

strip=
for s in $(cut -d' ' -f1 "$OUT.syms"); do
	strip="$strip --strip-symbol=__ksymtab_$s --strip-symbol=__kstrtab_$s"
done
rm -f "$OUT.syms"
# shellcheck disable=SC2086 # option lists
"$OBJCOPY" --redefine-syms="$RENAMES" \
	--remove-section=__ksymtab --remove-section=.rel__ksymtab \
	--remove-section=__ksymtab_gpl --remove-section=.rel__ksymtab_gpl \
	--remove-section=__ksymtab_strings $strip \
	"$IN" "$OUT"
